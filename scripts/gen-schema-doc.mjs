// Regenerates docs/schema.md from src/core/types.ts and checks that every schema bump has a migration.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const types = readFileSync("src/core/types.ts", "utf8");
const migrate = readFileSync("src/core/migrate.ts", "utf8");

const version = Number(/export const SCHEMA_VERSION = (\d+);/.exec(types)?.[1]);
if (!Number.isInteger(version)) { console.error("FAIL: could not read SCHEMA_VERSION"); process.exit(1); }

const table = /export const MIGRATIONS[^=]*=\s*\{([\s\S]*?)\n\};/.exec(migrate)?.[1] ?? "";
const have = new Set([...table.matchAll(/^\s{2}(\d+):/gm)].map((m) => Number(m[1])));
const missing = [];
for (let v = 1; v < version; v++) if (!have.has(v)) missing.push(`${v} -> ${v + 1}`);

mkdirSync("docs", { recursive: true });
writeFileSync("docs/schema.md", `# Stack document schema (version ${version})

Generated by \`scripts/gen-schema-doc.mjs\` from \`src/core/types.ts\`. Do not edit by hand.
Every change to this schema bumps \`SCHEMA_VERSION\` and adds a migration in \`src/core/migrate.ts\`.

Migrations present: ${[...have].sort((a, b) => a - b).map((v) => `${v} -> ${v + 1}`).join(", ") || "none"}

\`\`\`ts
${types.trim()}
\`\`\`
`);
console.log(`docs/schema.md written for schema version ${version}`);
if (missing.length) {
  console.error(`FAIL: no migration for ${missing.join(", ")}. Add it to MIGRATIONS in src/core/migrate.ts.`);
  process.exit(1);
}
